"""Run against a fresh, isolated test instance; never point at production."""
import os
import calendar
from pathlib import Path
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo
from playwright.sync_api import sync_playwright, expect

URL=os.environ.get('TEST_URL','http://127.0.0.1:8001')
OUT=Path(os.environ.get('SCREENSHOT_DIR','/tmp/contentos-screenshots'));OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1050})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(URL)
    page.get_by_label('Seu e-mail').fill('nmlouzada14@gmail.com')
    page.get_by_label('Senha',exact=True).fill('Initial-Test-2026!')
    page.get_by_role('button',name='Entrar no ContentOS').click()
    page.get_by_label('Senha inicial').fill('Initial-Test-2026!')
    page.get_by_label('Nova senha pessoal').fill('Personal-Test-2026!')
    page.get_by_role('button',name='Salvar senha e entrar').click()
    expect(page.get_by_role('heading',name='Sua produção, em um olhar.')).to_be_visible()
    page.locator('[data-page=settings]').click()
    page.get_by_role('button',name='Adicionar pessoa').click()
    page.get_by_label('Nome',exact=True).fill('Equipe de teste')
    page.get_by_label('E-mail',exact=True).fill('social@example.com')
    page.get_by_label('Cargo').fill('Social media')
    page.locator('#modal').get_by_role('button',name='Adicionar pessoa').click()
    expect(page.get_by_text('social@example.com',exact=True)).to_be_visible()
    page.locator('.nav [data-page=editorial]').click()
    page.get_by_role('button',name='Criar canal').click()
    page.get_by_label('Nome do canal').fill('Instagram · demonstração')
    page.get_by_label('Link do canal').fill('https://instagram.com/example')
    page.locator('#modal').get_by_role('button',name='Criar canal',exact=True).click()
    expect(page.get_by_role('heading',name='Instagram · demonstração')).to_be_visible()
    page.get_by_role('button',name='Criar formato').click()
    page.get_by_label('Nome do formato').fill('Reels · demonstração')
    page.get_by_role('checkbox',name='Instagram · demonstração',exact=True).check()
    page.get_by_role('checkbox',name='Equipe de teste',exact=True).check()
    today=datetime.now(ZoneInfo('America/Sao_Paulo')).date()
    monday=today-timedelta(days=today.weekday())
    page.get_by_label('Começar em').fill(str(monday))
    for i in range(7):page.locator('#freq-'+str(i)).fill('2')
    page.get_by_role('button',name='Criar formato e entregas').click()
    expect(page.locator('#modal')).not_to_be_visible()
    page.locator('.nav [data-page=tasks]').click()
    expect(page.locator('tr[data-task]')).to_have_count(14)
    page.locator('tr[data-task]').first.click()
    page.get_by_label('Descrição e links').fill('Briefing de teste https://example.com')
    page.get_by_label('Status',exact=True).select_option('Em andamento')
    page.locator('#file').set_input_files({'name':'briefing.txt','mimeType':'text/plain','buffer':b'Conteudo de teste'})
    page.get_by_role('button',name='Salvar alterações').click()
    expect(page.locator('#modal')).not_to_be_visible()
    page.locator('tr[data-task]').first.click()
    expect(page.get_by_role('link',name='briefing.txt')).to_be_visible()
    page.get_by_role('button',name='Fechar',exact=True).click()
    page.get_by_role('button',name='Kanban',exact=False).click()
    card=page.locator('.task-card').first
    title=card.locator('h3').inner_text()
    card.drag_to(page.locator('[data-drop="Revisão"]'))
    expect(page.locator('[data-drop="Revisão"]')).to_contain_text(title)
    page.screenshot(path=str(OUT/'kanban.png'),full_page=True)
    page.locator('.nav [data-page=calendar]').click()
    expect(page.locator('.calendar-event')).to_have_count(14)
    page.get_by_role('button',name='Mês',exact=True).click()
    expect(page.locator('.calendar.month')).to_be_visible()
    expect(page.locator('.calendar-day')).to_have_count(len(calendar.monthcalendar(monday.year,monday.month))*7)
    page.get_by_role('button',name='Dia',exact=True).click()
    expect(page.locator('.calendar-day')).to_have_count(1)
    page.get_by_role('button',name='Semana',exact=True).click()
    page.screenshot(path=str(OUT/'calendar.png'),full_page=True)
    page.locator('.nav [data-page=dashboard]').click()
    expect(page.locator('.stat')).to_have_count(6)
    page.screenshot(path=str(OUT/'dashboard.png'),full_page=True)
    page.locator('.nav [data-page=tasks]').click()
    page.get_by_role('button',name='Lista',exact=False).click()
    page.get_by_role('button',name='Criar tarefa',exact=False).first.click()
    page.get_by_label('Título',exact=True).fill('Tarefa manual de teste')
    page.get_by_label('Quantidade total de tarefas').fill('3')
    page.get_by_role('button',name='Criar tarefa(s)').click()
    expect(page.locator('#modal')).not_to_be_visible()
    expect(page.locator('tr[data-task]')).to_have_count(17)
    page.get_by_label('Filtrar status').select_option('Revisão')
    expect(page.locator('tr[data-task]')).to_have_count(1)
    page.get_by_label('Filtrar status').select_option('')
    page.reload()
    expect(page.get_by_role('heading',name='Sua produção, em um olhar.')).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(OUT/'mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Overflow mobile'
    # Independent browser session: team access sees same tasks and cannot manage users.
    other=browser.new_context(viewport={'width':1280,'height':800})
    member=other.new_page();member.goto(URL)
    member.get_by_label('Seu e-mail').fill('social@example.com')
    member.get_by_label('Senha',exact=True).fill('Initial-Test-2026!')
    member.get_by_role('button',name='Entrar no ContentOS').click()
    member.get_by_label('Senha inicial').fill('Initial-Test-2026!')
    member.get_by_label('Nova senha pessoal').fill('Personal-Social-2026!')
    member.get_by_role('button',name='Salvar senha e entrar').click()
    expect(member.get_by_role('heading',name='Sua produção, em um olhar.')).to_be_visible()
    expect(member.locator('[data-page=settings]')).to_have_count(0)
    member.locator('.nav [data-page=tasks]').click()
    expect(member.locator('tr[data-task]')).to_have_count(17)
    assert not errors,errors
    browser.close()
print('PASS: browser workflow, drag-and-drop, recurrence, uploads, calendar, filters, mobile, two sessions. Screenshots:',OUT)
