"""Run against a fresh isolated instance, never production."""
import os
from playwright.sync_api import sync_playwright, expect
URL=os.environ.get('TEST_URL','http://127.0.0.1:8007')
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context();page=context.new_page();errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(URL)
    page.get_by_label('Seu e-mail').fill('nmlouzada14@gmail.com')
    page.get_by_label('Senha',exact=True).fill('Initial-Test-2026!')
    page.get_by_role('button',name='Entrar no ContentOS').click()
    page.get_by_label('Senha inicial').fill('Initial-Test-2026!')
    page.get_by_label('Nova senha pessoal').fill('Personal-Test-2026!')
    page.get_by_role('button',name='Salvar senha e entrar').click()
    expect(page.get_by_role('heading',name='Sua produção, em um olhar.')).to_be_visible()
    def req(path,body=None):
        r=context.request.fetch(URL+'/api'+path,method='POST' if body is not None else 'GET',data=body,headers={'X-ContentOS':'1'})
        assert r.ok,r.text()
        return r.json()
    req('/channels',{'name':'Canal original','url':'https://example.com','color':'#123456'})
    state=req('/state');ch=state['channels'][0]['id'];today=state['today']
    req('/tasks',{'title':'Entrega teste','deadline':today,'channel_ids':[ch],'quantity':3})
    page.locator('.nav [data-page=editorial]').click()
    page.locator('[data-edit-channel]').click()
    page.get_by_label('Nome do canal').fill('Canal editado')
    page.get_by_role('button',name='Salvar alterações',exact=True).click()
    expect(page.locator('.channel-card')).to_contain_text('Canal editado')
    page.locator('[data-delete-channel]').click()
    page.get_by_role('button',name='Cancelar',exact=True).click()
    expect(page.locator('.channel-card')).to_have_count(1)
    page.locator('[data-delete-channel]').click()
    page.get_by_role('button',name='Excluir canal',exact=True).click()
    expect(page.locator('.channel-card')).to_have_count(0)
    page.locator('.nav [data-page=tasks]').click()
    expect(page.locator('tr[data-task]')).to_have_count(3)
    page.locator('tr[data-task]').first.click()
    expect(page.get_by_role('checkbox',name='Canal editado (excluído)')).to_be_checked()
    page.get_by_role('button',name='Excluir tarefa',exact=True).click()
    page.get_by_role('button',name='Confirmar exclusão').click()
    expect(page.locator('tr[data-task]')).to_have_count(2)
    page.locator('[data-select-table]').check()
    expect(page.locator('#modal')).not_to_be_visible()
    expect(page.locator('#delete-selected')).to_contain_text('(2)')
    page.locator('#delete-selected').click()
    expect(page.locator('.delete-preview li')).to_have_count(2)
    page.get_by_role('button',name='Cancelar',exact=True).click()
    expect(page.locator('tr[data-task]')).to_have_count(2)
    page.locator('#delete-selected').click()
    page.get_by_role('button',name='Confirmar exclusão').click()
    expect(page.locator('tr[data-task]')).to_have_count(0)
    assert req('/state')['tasks']==[]
    assert not errors,errors
    browser.close()
print('PASS: channel edit/delete, historical channel, single/bulk task deletion and cancellation.')
